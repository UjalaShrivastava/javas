// while----------

let i = 0;
while (i <= 10) {
    // console.log(`the value of i will be: ${i}`);
    i = i+3
}


let flowers = ["lily", "rose", "tulip", "lotus", "sunflower"]
let arr = 0;
while (arr < flowers.length) {
    // console.log(`flowers are: ${flowers[arr]}`);
    arr = arr + 1
}



// do while-------------

let amount = 1;
do {
    // console.log(`amount is ${amount}`);
    amount++
} while (amount <= 20);



